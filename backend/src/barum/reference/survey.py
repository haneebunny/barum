"""소비자 설문조사 결과의 사용 가능 여부 판별 (create 모드).

**설문조사는 실증자료가 아니다.** 「화장품 표시·광고 관리 지침」[별표2]가 인정하는
실증 수단은 인체적용시험 자료·인체외시험 자료·시험분석 자료·기능성화장품 심사(보고)
자료뿐이고, 소비자 설문은 목록에 없다. 특히 [별표2] 2.는 효능·효과 주장의 예시로
"수분감 30% 개선 효과, 피부결 20% 개선, 2주 경과 후 피부톤 개선"을 들면서 **인체적용
시험 또는 인체외시험 자료로 입증**하라고 못박는다. 설문으로는 대체되지 않는다.

그래서 여기서는 두 가지만 한다.
1. 설문 문구가 **피부 변화(효능)를 말하는지** 판별한다. 말하면 못 쓴다.
2. 못 쓰는 이유를 사용자에게 그대로 돌려준다(조용히 빠지지 않게).

**경계는 "피부 변화 주장은 전부 효능"이다**(팀장 확정, 2026-08-20). 기능성 3종
(미백·주름개선·자외선차단)만 막는 게 아니다. 보습·결·탄력처럼 고시 기능성이 아닌
것도 [별표2] 2.의 효능·효과에 해당하므로 설문으로 못 받친다. 안전한 쪽으로 잡았다.

쓸 수 있는 건 피부와 무관한 항목이다: 향·발림성·용기·재구매의향·가격만족도 등.
"""

import re

# 피부 변화를 가리키는 말. 하나라도 있으면 효능 주장으로 본다.
#
# 출처를 섞지 않았다: 아래 세 묶음은 각각 근거가 다르다.
# (1) 기능성 3종 - functional_ingredients.json의 categories 키
# (2) [별표2] 2.가 효능 예시로 직접 든 표현 - 수분감·피부결·피부톤
# (3) judge_rules.json needs_review["1호_의약품오인"]에 이미 등재된 피부상태 표현
_EFFICACY_TERMS: tuple[str, ...] = (
    # (1) 고시 기능성 3종
    "미백", "주름", "자외선차단", "선케어", "자외선 차단",
    # (2) 지침 [별표2] 2. 효능 예시
    "수분감", "피부결", "피부톤", "피부 톤",
    # (3) 그 밖의 피부 상태 변화
    "보습", "촉촉", "탄력", "잡티", "기미", "주근깨", "모공", "각질",
    "홍조", "트러블", "여드름", "피부 장벽", "피부장벽", "진정",
    "피부가", "피부는", "피붓결", "안색", "화이트닝", "브라이트닝",
)

# 피부 변화 동사. 위 명사 없이도 "개선됐다"류 단정이 붙으면 효능으로 본다.
_CHANGE_VERBS: tuple[str, ...] = (
    "개선", "좋아", "밝아", "맑아", "매끄러", "정돈", "완화", "감소", "줄어",
)

_SPACE_RE = re.compile(r"\s+")


def _normalize(text: str) -> str:
    """비교용 정규화. 띄어쓰기 흔들림을 없앤다."""
    return _SPACE_RE.sub("", text or "").lower()


def is_efficacy_survey(claim: str) -> bool:
    """설문 문구가 피부 변화(효능)를 주장하는지 본다.

    피부 관련 명사가 있으면 바로 효능으로 본다. 명사가 없어도 변화 동사만으로
    "무엇이" 좋아졌는지 모호하면 역시 효능 쪽으로 본다(안전한 쪽).
    """
    norm = _normalize(claim)
    if any(_normalize(t) in norm for t in _EFFICACY_TERMS):
        return True
    return any(v in norm for v in _CHANGE_VERBS)


def survey_sentence(evidence) -> str:
    """설문 결과 한 건을 문장으로 만든다. **LLM을 태우지 않는다.**

    수치를 지어낼 여지를 없애려고 입력값을 그대로 조립한다(clinical_sections_text와
    같은 원칙). 방법·표본·시기·기관을 반드시 함께 적는다 — 판정기가 "설문방법·표본·
    시기·출처 등 근거 제시가 없어 객관적 확인 필요"를 5호 사유로 들기 때문이다
    (2026-08-20 실측).
    """
    return (
        f"{evidence.claim} {evidence.value} "
        f"({evidence.institution}, {evidence.period}, {evidence.sample_size} 대상 {evidence.method})"
    )
